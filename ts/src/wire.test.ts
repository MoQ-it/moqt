import { readFileSync } from "node:fs";
import { describe, expect, test } from "vitest";
import { FetchDecoder, FetchRange, readSubgroupHeader, StreamReader, SubgroupDecoder } from "./stream.ts";
import {
  decodeMessage,
  decodeToken,
  encodeDatagram,
  encodeMessage,
  encodeSubgroupHeader,
  encodeToken,
  FilterType,
  type KeyValue,
  type Message,
  MsgType,
  ObjectStatus,
  parseDatagram,
  readKeyValues,
  readNamespace,
  Reader,
  renderNamespace,
  renderTrack,
  SessionError,
  SetupOption,
  StreamCountUnknown,
  SubgroupEncoder,
  type SubgroupHeader,
  Writer,
  writeKeyValues,
  writeNamespace,
} from "./wire.ts";

const vectors = (name: string) => JSON.parse(readFileSync(new URL(`../../testdata/v22/${name}`, import.meta.url), "utf8"));
const hex = (b: Uint8Array) => Buffer.from(b).toString("hex");
const unhex = (s: string) => new Uint8Array(Buffer.from(s, "hex"));
const prim = vectors("primitives.json");

function streamOf(b: Uint8Array): StreamReader {
  return new StreamReader(new ReadableStream({ start(c) { c.enqueue(b.slice(0, 3)); c.enqueue(b.slice(3)); c.close(); } }));
}

describe("varint", () => {
  test.each(prim.varints)("$hex = $value", (v: { hex: string; value: string; minimal: boolean }) => {
    const want = BigInt(v.value);
    expect(new Reader(unhex(v.hex)).varint64()).toBe(want);
    if (want <= BigInt(Number.MAX_SAFE_INTEGER)) expect(new Reader(unhex(v.hex)).varint()).toBe(Number(want));
    if (v.minimal) {
      expect(hex(new Writer().varint(want).finish())).toBe(v.hex);
      if (want <= BigInt(Number.MAX_SAFE_INTEGER)) expect(hex(new Writer().varint(Number(want)).finish())).toBe(v.hex);
    }
  });

  test("random round trip", () => {
    for (let i = 0; i < 20000; i++) {
      const v = Math.floor(Math.random() * 2 ** Math.floor(Math.random() * 53));
      expect(new Reader(new Writer().varint(v).finish()).varint()).toBe(v);
    }
  });
});

test("key values", () => {
  for (const g of prim.keyValues) {
    const kvs: KeyValue[] = g.pairs.map((p: { type: string; int?: string; bytesHex?: string }) =>
      Number(p.type) % 2 === 0 ? { type: Number(p.type), int: Number(p.int) } : { type: Number(p.type), bytes: unhex(p.bytesHex!) });
    expect(hex(writeKeyValues(new Writer(), [kvs[3], kvs[0], kvs[1], kvs[2]]).finish())).toBe(g.hex);
    expect(readKeyValues(new Reader(unhex(g.hex)))).toEqual(kvs);
  }
});

test("namespaces and rendering", () => {
  for (const n of prim.namespaces) {
    expect(hex(writeNamespace(new Writer(), n.fields).finish())).toBe(n.hex);
    expect(readNamespace(new Reader(unhex(n.hex)))).toEqual(n.fields);
    expect(renderNamespace(n.fields)).toBe(n.rendered);
  }
  for (const r of prim.renderedNames) expect(renderTrack({ namespace: r.namespace, name: r.track })).toBe(r.rendered);
  expect(() => readNamespace(new Reader(writeNamespace(new Writer(), ["a", ""]).finish()))).toThrow(SessionError);
});

test("tokens", () => {
  for (const t of prim.tokens) {
    const tok = {
      aliasType: t.aliasType,
      ...(t.alias !== undefined && { alias: Number(t.alias) }),
      ...(t.type !== undefined && { type: Number(t.type), value: unhex(t.valueHex) }),
    };
    expect(hex(encodeToken(tok))).toBe(t.hex);
    expect(decodeToken(unhex(t.hex))).toEqual(tok);
  }
});

test("golden messages", () => {
  const want: Record<string, Message> = {
    "SUBSCRIBE moqit/r1 mic, priority 16, next-object filter": {
      type: MsgType.Subscribe, requestId: 0, track: { namespace: ["moqit", "r1"], name: "mic" },
      params: { subscriberPriority: 16, locationFilter: { type: FilterType.NextObject } },
    },
    "SETUP with PATH=/moq and MOQT_IMPLEMENTATION=moqt-go": {
      type: MsgType.Setup,
      options: [{ type: SetupOption.Path, bytes: new TextEncoder().encode("/moq") }, { type: SetupOption.Implementation, bytes: new TextEncoder().encode("moqt-go") }],
    },
  };
  for (const v of vectors("messages.json").messages) {
    expect(hex(encodeMessage(want[v.name]))).toBe(v.hex);
    expect(decodeMessage(unhex(v.hex))).toEqual(want[v.name]);
  }
});

test("messages generated by the Go encoder decode and re-encode identically", () => {
  const generated = vectors("generated.json");
  expect(generated.messages.length).toBeGreaterThan(15);
  for (const v of generated.messages as { name: string; hex: string }[]) {
    const m = decodeMessage(unhex(v.hex));
    expect(hex(encodeMessage(m)), v.name).toBe(v.hex);
  }
  const done = generated.messages.find((v: { name: string }) => v.name === "PublishDone");
  expect((decodeMessage(unhex(done.hex)) as { streamCount: bigint }).streamCount).toBe(StreamCountUnknown);
});

test("message violations", () => {
  const sub = unhex(vectors("messages.json").messages[0].hex);
  const long = new Uint8Array([...sub, 0]);
  long[2]++;
  expect(() => decodeMessage(long)).toThrow(/trailing/);
  expect(() => decodeMessage(new Uint8Array([0x1e, 0, 0]))).toThrow(/unknown message type/);
});

describe("data plane", () => {
  const data = vectors("data.json");

  test("subgroup stream", async () => {
    const h: SubgroupHeader = { trackAlias: 1, group: 5, idMode: 0, subgroupId: 0, priority: 16, properties: false, endOfGroup: false, firstObject: false };
    const objs = [
      { id: 0, status: 0, payload: new TextEncoder().encode("a") },
      { id: 1, status: 0, payload: new TextEncoder().encode("bc") },
      { id: 3, status: ObjectStatus.EndOfGroup, payload: new Uint8Array() },
    ];
    const enc = new SubgroupEncoder(h);
    const w = new Writer().bytes(encodeSubgroupHeader(h));
    for (const o of objs) enc.encode(o, w);
    expect(hex(w.finish())).toBe(data.subgroupStreams[0].hex);

    const r = streamOf(unhex(data.subgroupStreams[0].hex));
    const gotHeader = await readSubgroupHeader(r, await r.varint());
    expect(gotHeader).toEqual(h);
    const dec = new SubgroupDecoder(r, gotHeader);
    for (const o of objs) expect(await dec.next()).toEqual({ ...o, properties: undefined });
    expect(await dec.next()).toBeUndefined();
  });

  test("FIN inside an object is a protocol violation", async () => {
    const h: SubgroupHeader = { trackAlias: 1, group: 1, idMode: 0, subgroupId: 0, properties: false, endOfGroup: false, firstObject: false };
    const b = new SubgroupEncoder(h).encode({ id: 0, status: 0, payload: new Uint8Array(5) }).finish();
    await expect(new SubgroupDecoder(streamOf(b.slice(0, -2)), h).next()).rejects.toThrow(/inside an object/);
  });

  test("fetch stream", async () => {
    const te = new TextEncoder();
    const o = { range: 0, datagram: false, subgroupId: 0, properties: undefined };
    const want = [
      { ...o, group: 5, object: 0, priority: 16, payload: te.encode("a") },
      { ...o, group: 5, object: 1, priority: 16, payload: te.encode("bc") },
      { range: FetchRange.NonExistent, group: 7, object: 0, datagram: false, subgroupId: 0, priority: 0, payload: new Uint8Array() },
      { ...o, group: 8, object: 2, subgroupId: 1, priority: 16, payload: te.encode("z") },
      { ...o, group: 8, object: 3, datagram: true, subgroupId: 0, priority: 32, payload: new Uint8Array() },
    ];
    const r = streamOf(unhex(data.fetchStreams[0].hex));
    expect(await r.varint()).toBe(0x05);
    expect(await r.varint()).toBe(3);
    const dec = new FetchDecoder(r);
    for (const w of want) expect(await dec.next()).toEqual(w);
    expect(await dec.next()).toBeUndefined();
    await expect(new FetchDecoder(streamOf(new Uint8Array([0x00, 0x01, 0x61]))).next()).rejects.toThrow(/first fetch entry/);
  });

  test("datagrams", () => {
    const want = [
      { trackAlias: 2, group: 7, object: 0, status: 0, payload: new TextEncoder().encode("hi") },
      { trackAlias: 2, group: 7, object: 4, priority: 32, status: ObjectStatus.EndOfGroup, payload: new Uint8Array() },
    ];
    data.datagrams.forEach((v: { hex: string }, i: number) => {
      expect(hex(encodeDatagram(want[i]))).toBe(v.hex);
      expect(parseDatagram(unhex(v.hex))).toEqual(want[i]);
    });
    expect(() => parseDatagram(new Uint8Array([0x10, 1, 1]))).toThrow(SessionError);
    expect(() => parseDatagram(new Uint8Array([0x22, 1, 1, 1, 0]))).toThrow(SessionError);
  });
});
